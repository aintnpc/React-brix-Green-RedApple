type TranslationKey = keyof typeof translations

// ─── t() helper ────────────────────────────────────────────────────────────

let _lang: Lang | null = null

function getLang(): Lang {
  if (_lang === null) _lang = detectLang()
  return _lang
}

export function isKorean(): boolean {
  return getLang() === 'ko'
}

export { getLang }

export function t(key: TranslationKey, ...args: any[]): string {
  const lang = getLang()
  const entry = translations[key] as any
  if (!entry) return key

  // Array values (day_names)
  if (Array.isArray(entry[lang])) {
    return entry[lang] as any
  }

  const val = entry[lang] ?? entry['en'] ?? entry['ko']
  if (typeof val === 'function') {
    return val(...args)
  }
  return val as string
}

// For array-returning keys like day_names
export function ta(key: TranslationKey): string[] {
  const lang = getLang()
  const entry = translations[key] as any
  const val = entry[lang] ?? entry['en'] ?? entry['ko']
  if (Array.isArray(val)) return val
  return []
}

// Reset cache (useful for testing / language switching at runtime)
export function resetLangCache() {
  _lang = null
}
