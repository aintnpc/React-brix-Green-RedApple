import { getLocales } from 'expo-localization'

// Supported languages
type Lang = 'ko' | 'en' | 'ja' | 'zh'

function detectLang(): Lang {
  try {
    const code = getLocales()[0]?.languageCode ?? 'ko'
    if (code === 'ja') return 'ja'
    if (code === 'zh') return 'zh'
    if (code === 'ko') return 'ko'
    return 'en'
  } catch {
    return 'ko'
  }
}

